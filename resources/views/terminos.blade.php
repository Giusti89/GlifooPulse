        <p>El Servicio ofrece distintos planes de suscripción, incluyendo planes gratuitos y planes de pago con
            diferentes niveles de funcionalidad.

            Los pagos se realizan mediante código QR enviado al número de celular registrado.

            El sistema notificará al usuario 5 días antes del vencimiento de su suscripción.

            La renovación se realiza a solicitud del usuario. No existen renovaciones automáticas.

            En caso de error en la elección del plan, se podrá solicitar un reembolso parcial o total dentro de las 24
            horas posteriores al pago, escribiendo a pulse@glifoo.com.
